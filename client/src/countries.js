const flagOf = (code) => String.fromCodePoint(...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));

let names = null;
try { names = new Intl.DisplayNames(['en'], { type: 'region' }); } catch { names = null; }

export const COUNTRIES = CODES
  .map((code) => ({ code, name: names?.of(code) ?? code, flag: flagOf(code) }))
  .filter((c) => c.name && c.name !== c.code)
  .sort((a, b) => a.name.localeCompare(b.name));

const byName = new Map(COUNTRIES.map((c) => [c.name.toLowerCase(), c]));
export const countryOf = (name) => (name ? byName.get(String(name).trim().toLowerCase()) ?? null : null);
// "🇧🇷 Brazil" when the country is known, else the text as typed.
export const countryLabel = (name) => { const c = countryOf(name); return c ? `${c.flag} ${c.name}` : name; };
